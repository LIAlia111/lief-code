export type LucideProps = ComponentPropsWithRef<"svg"> & {
  size?: string | number;
  absoluteStrokeWidth?: boolean;
};

const DEFAULT_ICON_SIZE = 24;

export function createIcon(Icon: Icon, orientationClass?: string) {
  return forwardRef<SVGSVGElement, LucideProps>(function PhosphorIcon(
    {
      size = DEFAULT_ICON_SIZE,
      color = "currentColor",
      strokeWidth = 2,
      absoluteStrokeWidth,
      ...props
    },
    ref,
  ) {
    const width = Number(strokeWidth);
    const absoluteSize = absoluteStrokeWidth ? Number(size) : 0;
    // CSS lengths cannot be normalized to Lucide's 24-unit viewBox at render time.
    const scaledWidth =
      absoluteSize > 0 && Number.isFinite(absoluteSize)
        ? (width * DEFAULT_ICON_SIZE) / absoluteSize
        : width;
    const weight = props.className?.split(/\s+/).includes("fill-current")
      ? "fill"
      : scaledWidth <= 1.25
        ? "light"
        : scaledWidth > 2.25
          ? "bold"
          : "regular";
    const decorative =
      !props.children &&
      !Object.keys(props).some(
        (key) => key.startsWith("aria-") || key === "role" || key === "title",
      );
    return (
      <Icon
        aria-hidden={decorative || undefined}
        {...props}
        color={color}
        className={
          orientationClass
            ? [orientationClass, props.className].filter(Boolean).join(" ")
            : props.className
        }
        ref={ref}
        size={size}
        weight={weight}
      />
    );
  });
}

